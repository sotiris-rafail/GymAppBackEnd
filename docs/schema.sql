-- Reference copy of the schema that Liquibase creates (db/changelog/changes/001-initial-schema.yaml).
-- Documentation only: the application never runs this file. Written in H2/PostgreSQL-compatible SQL.

CREATE TABLE plan (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name             VARCHAR(40)    NOT NULL,
    price            DECIMAL(10,2)  NOT NULL,
    visits_per_month INT            NOT NULL,
    unlimited        BOOLEAN        DEFAULT FALSE NOT NULL,   -- no visit limit; visits_per_month is then 0
    CONSTRAINT pk_plan PRIMARY KEY (id),
    CONSTRAINT ck_plan_values CHECK (price >= 0 AND visits_per_month >= 0)
);

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name          VARCHAR(60)  NOT NULL,
    email         VARCHAR(600) NOT NULL,       -- encrypted (AES-GCM, "v1:..."), key from the config server
    email_hash    VARCHAR(64),                 -- searchable fingerprint of the address (HMAC), unique
    password_hash VARCHAR(100) NOT NULL,       -- "p1$" + BCrypt of HMAC(secret salt, password)
    role          VARCHAR(10)  NOT NULL,
    plan_id       BIGINT,                      -- the plan held now; at most one
    CONSTRAINT pk_app_user PRIMARY KEY (id),
    CONSTRAINT uk_app_user_email_hash UNIQUE (email_hash),
    CONSTRAINT fk_app_user_plan FOREIGN KEY (plan_id) REFERENCES plan (id),
    CONSTRAINT ck_app_user_role CHECK (role IN ('MEMBER', 'ADMIN'))
);

CREATE TABLE gym_class (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name             VARCHAR(40) NOT NULL,
    coach            VARCHAR(40),
    start_time       TIME        NOT NULL,
    duration_minutes INT         NOT NULL,
    capacity         INT         NOT NULL,     -- max people per session
    CONSTRAINT pk_gym_class PRIMARY KEY (id),
    CONSTRAINT ck_gym_class_values CHECK (capacity >= 1 AND duration_minutes >= 1)
);

CREATE TABLE gym_class_day (
    gym_class_id BIGINT      NOT NULL,
    day_of_week  VARCHAR(12) NOT NULL,         -- MONDAY ... SUNDAY
    CONSTRAINT pk_gym_class_day PRIMARY KEY (gym_class_id, day_of_week),
    CONSTRAINT fk_gym_class_day_class FOREIGN KEY (gym_class_id) REFERENCES gym_class (id) ON DELETE CASCADE
);

CREATE TABLE booking (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id      BIGINT NOT NULL,
    gym_class_id BIGINT NOT NULL,
    session_date DATE   NOT NULL,
    CONSTRAINT pk_booking PRIMARY KEY (id),
    CONSTRAINT uk_booking_member_session UNIQUE (user_id, gym_class_id, session_date),
    CONSTRAINT fk_booking_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT fk_booking_class FOREIGN KEY (gym_class_id) REFERENCES gym_class (id) ON DELETE CASCADE
);
CREATE INDEX idx_booking_session   ON booking (gym_class_id, session_date);
CREATE INDEX idx_booking_user_date ON booking (user_id, session_date);

CREATE TABLE plan_history (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id          BIGINT                   NOT NULL,
    plan_name        VARCHAR(60)              NOT NULL,   -- copied, survives plan edits and deletion
    price            DECIMAL(10,2)            NOT NULL,
    visits_per_month INT                      NOT NULL,
    unlimited        BOOLEAN                  DEFAULT FALSE NOT NULL,
    started_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at         TIMESTAMP WITH TIME ZONE,            -- NULL while active
    CONSTRAINT pk_plan_history PRIMARY KEY (id),
    CONSTRAINT fk_plan_history_user FOREIGN KEY (user_id) REFERENCES app_user (id)
);
CREATE INDEX idx_plan_history_user ON plan_history (user_id, started_at);

CREATE TABLE promo (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    kind       VARCHAR(20)  NOT NULL,                 -- PHOTO, INSTAGRAM, PROMO, CARD or TILE
    title      VARCHAR(80)  NOT NULL,
    body       VARCHAR(500),
    image      CLOB,                                  -- http(s) address, or an uploaded image as a data URL
    link_url   VARCHAR(500),
    sort_order INT          NOT NULL DEFAULT 0,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    bordered   BOOLEAN      NOT NULL DEFAULT TRUE,   -- draw the tile with a border
    title_visible BOOLEAN   NOT NULL DEFAULT TRUE,   -- show the title on the tile
    hide_on    DATE,                                  -- not shown from this date on (NULL = no limit)
    col_span   INT          NOT NULL DEFAULT 0,       -- tile width in grid columns, 1-4 (0 = automatic)
    row_span   INT          NOT NULL DEFAULT 0,       -- tile height in grid rows, 1-3 (0 = automatic)
    bg_color   VARCHAR(7),                            -- tile background colour, #rrggbb
    bg_image   CLOB,                                  -- tile background picture (http(s) address or data URL)
    content    CLOB,                                  -- CARD only: full text (simple HTML) shown when the card is opened
    marketing            BOOLEAN NOT NULL DEFAULT FALSE,  -- the admin ticked "send as a marketing email"
    marketing_queued_at  TIMESTAMP WITH TIME ZONE,        -- when those emails were queued (null = not yet)
    marketing_recipients INT NOT NULL DEFAULT 0,          -- how many members they were queued for
    CONSTRAINT pk_promo PRIMARY KEY (id)
);

CREATE TABLE closed_day (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    closed_on DATE     NOT NULL,                       -- a date with no classes (Sundays are closed by rule, not stored)
    reason VARCHAR(80),
    CONSTRAINT pk_closed_day PRIMARY KEY (id),
    CONSTRAINT uq_closed_day UNIQUE (closed_on)
);

CREATE TABLE member_preference (
    user_id         BIGINT  NOT NULL,
    marketing       BOOLEAN NOT NULL DEFAULT FALSE,    -- marketing material
    new_plans       BOOLEAN NOT NULL DEFAULT FALSE,    -- a new plan is available
    plan_ending     BOOLEAN NOT NULL DEFAULT FALSE,    -- 2 visits remain this month
    visits_reminder BOOLEAN NOT NULL DEFAULT FALSE,    -- after the 21st, visits are still left
    CONSTRAINT pk_member_preference PRIMARY KEY (user_id),
    CONSTRAINT fk_member_preference_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE
);

CREATE TABLE closed_period (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    kind       VARCHAR(5) NOT NULL,                    -- WEEK or MONTH
    start_date DATE       NOT NULL,
    end_date   DATE       NOT NULL,
    CONSTRAINT pk_closed_period PRIMARY KEY (id)
);

CREATE TABLE app_setting (
    setting_key   VARCHAR(40)  NOT NULL,               -- e.g. booking.window (ANY, WEEK or MONTH)
    setting_value VARCHAR(200) NOT NULL,
    CONSTRAINT pk_app_setting PRIMARY KEY (setting_key)
);

