CREATE TABLE email_outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT        NOT NULL,
    kind            VARCHAR(20)   NOT NULL,            -- MARKETING, NEW_PLAN, PLAN_ENDING or VISITS_REMINDER
    dedupe_key      VARCHAR(60)   NOT NULL,            -- e.g. plan:7, ending:2026-10, campaign:3: one per member
    subject         VARCHAR(200)  NOT NULL,
    body            VARCHAR(4000) NOT NULL,
    status          VARCHAR(10)   NOT NULL,            -- PENDING, SENT, FAILED or SKIPPED
    attempts        INT           NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at         TIMESTAMP WITH TIME ZONE,
    last_error      VARCHAR(300),
    CONSTRAINT pk_email_outbox PRIMARY KEY (id),
    CONSTRAINT fk_email_outbox_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT uk_email_outbox_key UNIQUE (user_id, dedupe_key)   -- nobody gets the same email twice
);
CREATE INDEX idx_email_outbox_due ON email_outbox (status, next_attempt_at);

CREATE TABLE marketing_campaign (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    subject    VARCHAR(150)  NOT NULL,
    body       VARCHAR(3000) NOT NULL,
    link_url   VARCHAR(500),
    status     VARCHAR(10)   NOT NULL,                 -- DRAFT or SENT
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at    TIMESTAMP WITH TIME ZONE,
    recipients INT NOT NULL DEFAULT 0,                 -- how many members it was queued for
    CONSTRAINT pk_marketing_campaign PRIMARY KEY (id)
);


